"""Small Streamlit analytical client for the GeoPulse FastAPI service."""
import os
import requests
import streamlit as st

st.set_page_config(page_title="GeoPulse AI",page_icon="🗺️",layout="wide")
st.title("GeoPulse AI")
st.caption("Geospatial complaint recurrence intelligence · Predict. Prioritize. Prevent.")
api=os.getenv("GEOPULSE_API_URL","http://127.0.0.1:8000").rstrip("/")
try:
    health=requests.get(f"{api}/api/health",timeout=5).json()
    a,b=st.columns(2); a.metric("API status",health["status"]); b.metric("Trained model","Available" if health["model_available"] else "Not trained")
except requests.RequestException: st.error("API unavailable. Start the FastAPI service and retry.")
st.subheader("Cell-level recurrence estimate")
st.caption("Enter features generated by the training pipeline. Example values below are illustrative inputs, not model results.")
defaults={"count_7d":2.0,"count_30d":8.0,"count_90d":18.0,"mean_daily_30d":.267,"days_since_last":4.0,"day_of_week":1.0,"month":6.0,"x_km":580.0,"y_km":4500.0}
with st.form("prediction"):
    cols=st.columns(3); values={}
    for i,(key,value) in enumerate(defaults.items()): values[key]=cols[i%3].number_input(key,value=float(value))
    submitted=st.form_submit_button("Estimate recurrence risk")
if submitted:
    try:
        response=requests.post(f"{api}/api/predict",json={"features":values},timeout=30); response.raise_for_status()
        result=response.json(); st.metric("Estimated 30-day recurrence probability",f"{result['recurrence_probability']:.1%}")
        st.metric("Risk band",result["risk_level"]); st.json(result)
    except requests.RequestException as exc: st.error(f"Prediction failed: {exc}")
st.info("Spatial maps and model evaluation charts will be connected after the first real-data training run.")
